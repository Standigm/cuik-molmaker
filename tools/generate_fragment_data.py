"""Emit the ``fr_*`` fragment SMARTS of ``rdkit.Chem.Fragments`` as a C++ header.

The patterns are read the way ``Fragments._LoadPatterns`` reads them, from the RDKit
release this is run against, so the C++ counts stay in step with it. Run this when
bumping RDKit, format the header as the repository's hook does, and diff the result::

    python tools/generate_fragment_data.py > src/fragment_data.h
    clang-format -i src/fragment_data.h
"""

import sys

from rdkit import __version__ as rdkit_version
from rdkit.Chem import Fragments


def _cxx_string(text: str) -> str:
    """Render a string as a C++ string literal.

    A pattern on the last column of its line keeps the line's newline, exactly as
    _LoadPatterns hands it to MolFromSmarts, so control characters are escaped, not
    dropped.
    """
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return (
        '"'
        + escaped.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
        + '"'
    )


def _load_patterns() -> list[tuple[str, str]]:
    """(descriptor name, SMARTS) pairs in file order, parsed as _LoadPatterns does."""
    patterns = []
    with open(Fragments.defaultPatternFileName) as handle:
        for line in handle:
            if not line or line[0] == "#":
                continue
            fields = line.split("\t")
            if len(fields) >= 3:
                name = fields[0].replace("=", "_").replace("-", "_")
                patterns.append((name, fields[2]))
    return patterns


def main() -> None:
    """Write the header to stdout."""
    patterns = _load_patterns()
    installed = [name for name, _ in Fragments.fns]
    if [name for name, _ in patterns] != installed:
        raise SystemExit("parsed fragment names differ from rdkit.Chem.Fragments.fns")

    out = sys.stdout.write
    out(
        "// SPDX-FileCopyrightText: Copyright (c) 2025 NVIDIA CORPORATION"
        " & AFFILIATES. All rights reserved.\n"
        "// SPDX-License-Identifier: Apache-2.0\n\n"
        "//! @file Generated by tools/generate_fragment_data.py"
        " -- do not edit by hand.\n"
        f"//!       Transcribed from rdkit.Chem.Fragments of RDKit {rdkit_version}.\n\n"
        "#pragma once\n\n"
        "#include <array>\n\n"
        "namespace cuik_molmaker::fragment_data {\n\n"
        "//! One fr_* descriptor: the number of unique matches of its SMARTS.\n"
        "struct FragmentPattern {\n"
        "  const char* name;\n"
        "  const char* smarts;\n"
        "};\n\n"
        f"inline constexpr std::array<FragmentPattern, {len(patterns)}>"
        " FRAGMENT_PATTERNS = {{\n"
    )
    for name, smarts in patterns:
        entry = f"  {{{_cxx_string(name)}, {_cxx_string(smarts)}}},"
        if len(entry) <= 120:
            out(entry + "\n")
            continue
        # Adjacent literals concatenate, keeping the longest SMARTS inside 120 columns.
        chunks = [smarts[i : i + 100] for i in range(0, len(smarts), 100)]
        out(f"  {{{_cxx_string(name)},\n")
        out("".join(f"   {_cxx_string(chunk)}\n" for chunk in chunks[:-1]))
        out(f"   {_cxx_string(chunks[-1])}}},\n")
    out("}};\n\n}  // namespace cuik_molmaker::fragment_data\n")


if __name__ == "__main__":
    main()
